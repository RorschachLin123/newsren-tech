"""Cited briefing and the editorial gate.

The LLM only writes prose from claims that passed verification, citing sources by number.
The evidence table, labels and source list are rendered by code from the ledger, so every
citation points at a real retrieved source. Citations the LLM invents are stripped.
"""
import json
import re

from .llm import BudgetExceeded
from .store import OUT, iso, now, save_json, short_hash

LABEL_TEXT = {
    "independently_verified": "Independently verified",
    "disputed": "Disputed by independent evidence",
    "originator_claim_only": "Only the originator's claim (or re-reports of it)",
    "unverified": "Could not verify",
}
NOTICE = ("Generated by an AI research agent from the sources listed below. Labels are computed by fixed "
          "rules: a claim is 'independently verified' only if a source other than the developer of the model "
          "or product reports its own testing. Pending human editorial review before delivery.")


def _number_sources(claims):
    refs, order = {}, []
    for c in claims:
        for e in c["evidence"]:
            if e["stance"] == "irrelevant":
                continue
            if e["url"] not in refs:
                refs[e["url"]] = len(order) + 1
                order.append(e)
            e["ref"] = refs[e["url"]]
    return order


def _prose(llm, topic, matches, sources_list, note):
    shown = [{"claim": c["text"], "originator": c["originator"], "label": c["label"],
              "verification_note": c["note"], "why_it_meets_criteria": c.get("why", ""),
              "evidence": [{"ref": e["ref"], "publisher": e["publisher"], "stance": e["stance"],
                            "basis": e["basis"], "quote": e["quote"]}
                           for e in c["evidence"] if e["stance"] != "irrelevant"]} for c in matches]
    prompt = f"""Write a short news briefing for a reader who follows this question:
{topic['question']}
Audience: {topic.get('audience', 'professional')}. Plain, precise English. No hype.

Verified material (use nothing else):
{json.dumps(shown, indent=1, ensure_ascii=False)}

Rules: every factual sentence ends with citations like [1] or [2][3] using only the refs above.
Say who made each claim. Keep vendor claims and independent results clearly apart.

Return JSON: {{"headline": "...", "what_changed": "<2-4 sentences>", "why_it_matters": "<1-3 sentences>",
"watch_next": ["<one line>", "..."]}}"""
    try:
        out = llm.json(prompt)
    except BudgetExceeded as e:
        note(str(e))
        out = {"headline": "New verified development on your topic",
               "what_changed": " ".join(f"{c['text']} [{c['evidence'][0].get('ref', 1)}]" for c in matches),
               "why_it_matters": "", "watch_next": []}
    valid = {e["ref"] for e in sources_list}

    def clean(text):
        def keep(m):
            if int(m.group(1)) in valid:
                return m.group(0)
            note(f"removed invented citation {m.group(0)}")
            return ""
        return re.sub(r"\[(\d+)\]", keep, text or "")

    return {k: ([clean(x) for x in v] if isinstance(v, list) else clean(v)) for k, v in out.items()}


def write(llm, topic, record, checked, matches, ledger, note):
    stamp = now()
    alert = bool(matches)
    sources_list = _number_sources(checked)
    lines = [f"# {topic['question']}", ""]
    if alert:
        p = _prose(llm, topic, matches, sources_list, note)
        lines += [f"## {p.get('headline', 'Update')}", "",
                  f"**Status:** DRAFT, pending editorial review · generated {iso(stamp)} · audience: {topic.get('audience')}", "",
                  "### What changed", "", p.get("what_changed", ""), ""]
        if p.get("why_it_matters"):
            lines += ["### Why it matters", "", p["why_it_matters"], ""]
        if p.get("watch_next"):
            lines += ["### What to watch next", ""] + [f"- {w}" for w in p["watch_next"]] + [""]
    else:
        lines += [f"**No alert.** Nothing checked in this run met your criteria: {topic['alert_when']}", "",
                  f"Run finished {iso(stamp)}. This report is kept for the record and is not sent to the reader.", ""]

    lines += ["### Evidence check", "", "| Claim | Made by | Label | Sources |", "|---|---|---|---|"]
    for c in checked:
        refs = " ".join(f"[{e['ref']}]{'✓' if e['stance'] == 'supports' else '✗'}"
                        for e in c["evidence"] if e["stance"] != "irrelevant") or "none"
        upd = f" (was: {c['update_of']})" if c.get("update_of") else ""
        lines.append(f"| {c['text']} | {c['originator']} | {LABEL_TEXT[c['label']]}{upd} | {refs} |")
    if not checked:
        lines.append("| No new claims this run | | | |")
    lines += ["", "✓ supports, ✗ contradicts.", ""]

    gaps = [c for c in checked if c["label"] != "independently_verified"]
    if gaps:
        lines += ["### What we could not verify", ""] + [f"- {c['text']}: {c['note']}" for c in gaps] + [""]

    lines += ["### Sources", ""]
    for e in sources_list:
        flags = []
        if not e.get("approved_domain", True):
            flags.append("not on approved list, not counted")
        if (e.get("via") or "").startswith("data:"):
            flags.append("structured data row, sentence rendered by Newsren from the published data")
        if e["source_type"] == "paper":
            flags.append("preprint, not peer reviewed" if "arxiv.org" in e["domain"] else "paper")
        lines.append(f"{e['ref']}. [{e['title']}]({e['url']}) · {e['publisher']} ({e['source_type']}"
                     f"{'; ' + '; '.join(flags) if flags else ''}) · published {e['published'] or 'unknown'}"
                     f" · retrieved {e['retrieved_at']}")
    if not sources_list:
        lines.append("None.")
    lines += ["", "---", f"*{NOTICE}*", "",
              f"<sub>Run: {record['new_items']} new items, {len(checked)} claims checked, "
              f"{llm.calls} LLM calls, ${llm.cost_usd:.3f}.</sub>", ""]

    path = OUT / topic["id"] / f"{stamp.strftime('%Y-%m-%d_%H%M%S')}{'_ALERT' if alert else ''}.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines))
    if alert:
        ledger.data["briefings"].append({"id": "B" + short_hash(str(path)), "path": str(path),
                                         "claims": [m["id"] for m in matches],
                                         "status": "pending_review", "created_at": iso(stamp)})
    return path


def approve(ledger, topic_id, briefing_id, editor):
    """Editorial gate: only an approved briefing is delivered (here: appended to out/alerts.jsonl)."""
    for b in ledger.data["briefings"]:
        if b["id"] == briefing_id:
            if b["status"] != "pending_review":
                raise SystemExit(f"{briefing_id} is already {b['status']}")
            b.update(status="approved", approved_by=editor, approved_at=iso(now()))
            OUT.mkdir(exist_ok=True)
            with open(OUT / "alerts.jsonl", "a") as f:
                f.write(json.dumps({"topic": topic_id, "briefing": briefing_id, "path": b["path"],
                                    "delivered_at": b["approved_at"]}) + "\n")
            ledger.save()
            return b
    raise SystemExit(f"No briefing {briefing_id} for {topic_id}")
